"""The create layer: Drafts, the Editor, and the module protocol.

The usual import is ``from rise_origin import create as cr``. A module author
decorates a plain function with ``cr.module``, receives an editor access and
validated settings, and returns a detached ``cr.Draft``. A world author works
through a ``cr.Editor``: require materials, create drafts, insert them, and
compile world updates.

Math values are the engine-bound types used directly: ``RVec3rf``,
``RVec2rf``, ``RQuat3rf``, ``RMat3rf``, and ``RS_Version``.
"""

